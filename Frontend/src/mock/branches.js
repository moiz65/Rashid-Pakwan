const total = (list) => list.reduce((sum, i) => sum + i.qty * i.price, 0)

function order(id, branchId, customer, list, status, when, extra = {}) {
  return {
    id,
    branchId,
    isDemo: true,
    source: extra.source || 'website',
    customerId: customer.id,
    customerName: customer.name,
    items: list,
    total: total(list),
    status,
    createdAt: when,
    rejectionReason: extra.rejectionReason || null,
  }
}

